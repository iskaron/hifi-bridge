def idents(lic: str) -> list[str]:
    s = re.sub(r"\(([^)]*)\)", " ", lic)                     # "(libfoo)" component annotations
    parts = re.split(r",|\bor\b|\band\b|\bwith\b|/|;|\|", s)
    return [p.strip() for p in parts if p.strip()]


def main(path: str, board: str, out_md: str) -> int:
    info = json.load(open(path))
    rows, review = [], []
    for name, p in sorted(info.items()):
        if p.get("type") != "target" or p.get("virtual"):
            continue
        lic = (p.get("licenses") or "").strip()
        bad = [i for i in idents(lic) if i not in ALLOWED]
        status = "ok"
        if name in EXCEPTIONS:
            status = "exception"
        elif not lic or lic.lower() in ("unknown",):
            status = "REVIEW (no licence)"
        elif bad:
            status = "REVIEW (" + ", ".join(bad) + ")"
        rows.append((name, p.get("version", ""), lic or "-", status))
        if status.startswith("REVIEW"):
            review.append(name)
    with open(out_md, "w") as fh:
        fh.write(f"# Target packages and licences - {board}\n\nGenerated by os/tools/license_report.py from `make show-info` "
                 f"(Buildroot 2026.02.x @ 679b9ea). {len(rows)} target packages, {len(review)} to review.\n\n")
        fh.write("| Package | Version | Licence (Buildroot) | Policy |\n|---|---|---|---|\n")
        for r in rows:
            fh.write("| " + " | ".join(x.replace("|", "/") for x in r) + " |\n")
        if EXCEPTIONS:
            fh.write("\n## Reviewed exceptions\n" + "".join(f"* `{k}`: {v}\n" for k, v in EXCEPTIONS.items()))
    print(f"{board}: {len(rows)} target packages, {len(review)} need review" + (": " + ", ".join(review) if review else ""))
    return 1 if review else 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:4]))
