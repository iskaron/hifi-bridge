def hz(note: float) -> float:
    return 440.0 * 2.0 ** ((note - 69) / 12.0)


def _voice(freq: float, n: int, partials=((1, 1.0), (2, 0.32), (3, 0.12), (4, 0.05)), detune: float = 0.0) -> np.ndarray:
    t = np.arange(n) / RATE
    out = np.zeros(n)
    for k, amp in partials:
        out += amp * np.sin(2 * np.pi * freq * k * (1 + detune) * t)
    return out


def _pluck(freq: float, seconds: float, decay: float) -> np.ndarray:
    n = int(seconds * RATE)
    env = np.exp(-np.arange(n) / (decay * RATE))
    env[: min(n, 220)] *= np.linspace(0, 1, min(n, 220))           # 5 ms attack: no click
    return _voice(freq, n, ((1, 1.0), (2, 0.45), (3, 0.2), (5, 0.06))) * env


def _pad(notes, seconds: float) -> np.ndarray:
    n = int(seconds * RATE)
    env = np.ones(n)
    a = min(n // 3, int(0.6 * RATE))
    env[:a] = np.sin(np.linspace(0, np.pi / 2, a)) ** 2
    env[-a:] = np.cos(np.linspace(0, np.pi / 2, a)) ** 2
    out = sum(_voice(hz(m), n, detune=d) for m in notes for d in (-0.0015, 0.0015))
    return out * env / (2 * len(notes))


def _add(buf: np.ndarray, sig: np.ndarray, at: int, pan: float, gain: float) -> None:
    end = min(len(buf), at + len(sig))
    if end <= at:
        return
    s = sig[: end - at] * gain
    buf[at:end, 0] += s * np.cos((pan + 1) * np.pi / 4)
    buf[at:end, 1] += s * np.sin((pan + 1) * np.pi / 4)


PEAK = 0.89                                                         # -1 dBFS: loud, but with headroom for the DAC and for resampling
DRIVE = 1.0                                                         # gentle tanh saturation: about +4 dB RMS at the same peak


def _finish(buf: np.ndarray, peak: float = PEAK, fade_in: float = 1.0, fade_out: float = 2.0, drive: float = DRIVE) -> bytes:
    """Echo, fades, then a soft limiter and peak normalisation. Level policy (docs/DEMO.md "Loudness"): the generated pieces were -17.8 dBFS
    RMS / -3.1 dBFS peak, which behind Lyrion's default player volume 50 (-25 dB) arrived at about -42 dBFS - hardly audible. Now about
    -14 dBFS RMS / -1 dBFS peak, like moderately loud music."""
    d = int(0.29 * RATE)                                             # a soft ping-pong echo for width
    buf[d:, 0] += 0.22 * buf[:-d, 1]
    buf[d:, 1] += 0.22 * buf[:-d, 0]
    buf -= buf.mean(axis=0)
    fi, fo = int(fade_in * RATE), int(fade_out * RATE)
    buf[:fi] *= np.linspace(0, 1, fi)[:, None] ** 2
    buf[-fo:] *= np.linspace(1, 0, fo)[:, None] ** 2
    buf /= max(1e-9, np.abs(buf).max())
    if drive > 0:
        buf = np.tanh(drive * buf) / np.tanh(drive)
    buf *= peak / max(1e-9, np.abs(buf).max())
    return (np.clip(buf, -1, 1) * 32767).astype("<i2").tobytes()


def _compose(track: Track) -> np.ndarray:
    rng = np.random.default_rng(track.seed)
    beat = 60.0 / track.bpm
    n = int(round(track.seconds * RATE))
    buf = np.zeros((n, 2))
    for bar in range(track.bars):
        chord = track.chords[bar % len(track.chords)]
        t0 = bar * 4 * beat
        _add(buf, _pad(chord, 4 * beat + 0.4), int(t0 * RATE), 0.0, 0.55)
        for b in (0, 2):                                             # bass on beats 1 and 3
            _add(buf, _pluck(hz(chord[0] - 24), 1.6 * beat, 0.45), int((t0 + b * beat) * RATE), -0.15, 0.9)
        tones = [m + 12 for m in chord] + [chord[0] + 24]
        for step in range(8):                                        # arpeggio in eighths, gently varied
            if rng.random() < 0.12:
                continue
            note = tones[(step + bar) % len(tones)] if rng.random() > 0.2 else rng.choice(tones)
            swing = track.swing * beat / 2 if step % 2 else 0.0
            pan = 0.55 if step % 2 else -0.45
            _add(buf, _pluck(hz(note), 1.2 * beat, 0.32), int((t0 + step * beat / 2 + swing) * RATE), pan, track.lead * 0.5)
    return buf


@lru_cache(maxsize=8)
def render(track: Track) -> bytes:
    """The whole track as s16le stereo PCM (cached: ~10 MB per minute)."""
    return _finish(_compose(track))


def notification(seconds: float = 0.7) -> bytes:
    """A short two-note chime, as a messenger would play it."""
    n = int(seconds * RATE)
    buf = np.zeros((n, 2))
    _add(buf, _pluck(hz(88), seconds, 0.12), 0, -0.1, 1.0)
    _add(buf, _pluck(hz(93), seconds - 0.12, 0.14), int(0.12 * RATE), 0.1, 0.9)
    return _finish(buf, peak=0.8, fade_in=0.005, fade_out=0.05)


