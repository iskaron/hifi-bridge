"""Demo audio content, generated in code: a few short synthesised pieces, a notification chime and an endless "radio" programme.

No third-party recordings are used anywhere in the demo. The output of these generators is dedicated to the public domain (CC0-1.0);
the generator code itself is part of the project (AGPL-3.0-only). Everything is 44.1 kHz, 16-bit, stereo (what an A2DP sink delivers
after decoding).
"""
from __future__ import annotations

import time
from dataclasses import dataclass, field
from functools import lru_cache

import numpy as np

RATE = 44100
LICENCE = "Generated by hifidemo.music (no recordings); audio output CC0-1.0"


@dataclass(frozen=True)
class Track:
    id: str
    title: str
    artist: str
    album: str
    bpm: float
    chords: tuple                                    # MIDI notes per bar
    bars: int
    seed: int
    lead: float = 0.5                                # level of the arpeggio voice
    swing: float = 0.0
    tags: tuple = field(default=())

    @property
    def seconds(self) -> float:
        return self.bars * 4 * 60.0 / self.bpm


