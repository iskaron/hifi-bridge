class Radio:
    """An endless live programme: shows interleaved with a station jingle. A reader joins at the current wall-clock position."""

    def __init__(self, clock=time.time):
        parts = []
        for show in RADIO_SHOWS:
            parts += [render(show), self.jingle()]
        self._loop = b"".join(parts)
        self.jingle_seconds = len(self.jingle()) / (4 * RATE)
        self.cycle_seconds = len(self._loop) / (4 * RATE)
        self.frames = len(self._loop) // 4
        self.position = int(clock() * RATE) % self.frames           # in frames

    @staticmethod
    @lru_cache(maxsize=1)
    def jingle() -> bytes:
        buf = np.zeros((int(1.6 * RATE), 2))
        for i, m in enumerate((72, 76, 79, 84)):
            _add(buf, _pluck(hz(m), 1.6 - i * 0.18, 0.4), int(i * 0.18 * RATE), -0.3 + 0.2 * i, 0.9)
        return _finish(buf, peak=0.8, fade_in=0.005, fade_out=0.3)

    def read(self, nbytes: int) -> bytes:
        nbytes -= nbytes % 4
        out = bytearray()
        loop = self._loop
        while len(out) < nbytes:
            off = self.position * 4
            take = min(nbytes - len(out), len(loop) - off)
            out += loop[off: off + take]
            self.position = (self.position + take // 4) % (len(loop) // 4)
        return bytes(out)
