"""Render the configuration files the root network agent applies (pure functions; validated with the real tools in Docker, tests/net).

* ``wpa_supplicant.conf`` (client Wi-Fi), ``hostapd.conf`` (setup hotspot), ``dnsmasq.conf`` (DHCP for hotspot clients only),
* systemd-networkd ``.network`` files (Ethernet and Wi-Fi addresses: DHCP/static IPv4, SLAAC/DHCPv6/static/off IPv6, the hotspot address),
* the nftables ruleset (default deny inbound; docs/NETWORK.md "Firewall").

Injection safety: no SSID or password is ever written as text. SSIDs are hex (wpa_supplicant ``ssid=<hex>``, hostapd ``ssid2=<hex>``);
passwords become the WPA2 pairwise master key (PBKDF2-HMAC-SHA1(password, SSID, 4096), hex: ``psk=``/``wpa_psk=``) and, for WPA3-SAE,
``sae_password=<hex>``. (Found by the real wpa_supplicant in tests/net: it strips ``#`` comments outside quotes, so a quoted passphrase
containing ``"`` or ``#`` was silently truncated.) Everything is rendered from a configuration that ``netconfig.validate`` accepted.
"""
from __future__ import annotations

import hashlib

from .netconfig import HOTSPOT_ADDRESS, HOTSPOT_NETWORK

RUN_DIR = "/run/hifi-net"
NFT_TABLE = "hifi"
HOTSPOT_CHANNEL = 6                    # 2.4 GHz channel 6 is permitted in every regulatory domain (1-11 everywhere)
HOTSPOT_MAX_STATIONS = 8
DHCP_RANGE = ("10.42.0.10", "10.42.0.60")
LYRION_DISCOVERY_PORT = 3483


def _hex(s: str) -> str:
    return s.encode("utf-8").hex()


def pmk(passphrase: str, ssid: str) -> str:
    """IEEE 802.11i passphrase-to-PSK mapping (same result as ``wpa_passphrase``; checked against it in tests/net)."""
    return hashlib.pbkdf2_hmac("sha1", passphrase.encode("ascii"), ssid.encode("utf-8"), 4096, 32).hex()


def wpa_supplicant(wifi: dict, country: str, ctrl_dir: str = f"{RUN_DIR}/wpa") -> str:
    psk = wifi["psk"]
    hexkey = len(psk) == 64 and all(c in "0123456789abcdefABCDEF" for c in psk)
    lines = [
        "# generated by hifi-netd - do not edit (lives in RAM only)",
        f"ctrl_interface=DIR={ctrl_dir} GROUP=root",
        "update_config=0",
        f"country={country}",
        "ap_scan=1",
        "network={",
        f"\tssid={_hex(wifi['ssid'])}",
        f"\tscan_ssid={1 if wifi.get('hidden') else 0}",
    ]
    if hexkey:                         # a raw 256-bit PSK cannot be used for WPA3-SAE (SAE needs the password)
        lines += [f"\tpsk={psk.lower()}", "\tkey_mgmt=WPA-PSK WPA-PSK-SHA256", "\tieee80211w=1"]
    else:                              # WPA2, WPA2/WPA3 transition and WPA3-only networks; protected management frames when offered
        lines += [f"\tpsk={pmk(psk, wifi['ssid'])}", f"\tsae_password={_hex(psk)}", "\tkey_mgmt=WPA-PSK WPA-PSK-SHA256 SAE",
                  "\tieee80211w=1"]
    lines += ["}", ""]
    return "\n".join(lines)


def hostapd(hotspot: dict, country: str, iface: str, ctrl_dir: str = f"{RUN_DIR}/hostapd") -> str:
    return "\n".join([
        "# generated by hifi-netd - do not edit (lives in RAM only)",
        f"interface={iface}",
        "driver=nl80211",
        f"ctrl_interface={ctrl_dir}",
        "ctrl_interface_group=0",
        f"ssid2={_hex(hotspot['ssid'])}",
        "utf8_ssid=1",
        f"country_code={country}",
        "ieee80211d=1",
        "hw_mode=g",
        f"channel={HOTSPOT_CHANNEL}",
        "ieee80211n=1",
        "wmm_enabled=1",
        "auth_algs=1",
        "ignore_broadcast_ssid=0",
        # WPA2-PSK (CCMP) only: WPA3-SAE in AP mode depends on the Wi-Fi firmware and is a hardware-gate item (docs/NETWORK.md)
        "wpa=2",
        "wpa_key_mgmt=WPA-PSK",
        "rsn_pairwise=CCMP",
        f"wpa_psk={pmk(hotspot['psk'], hotspot['ssid'])}",
        "ap_isolate=1",                # hotspot clients cannot talk to each other
        f"max_num_sta={HOTSPOT_MAX_STATIONS}",
        "",
    ])


def dnsmasq(iface: str, run_dir: str = RUN_DIR) -> str:
    """DHCP for hotspot clients only. Deliberately NO DNS (port=0) and NO default route: phones see a local network without internet,
    no fake captive portal; the setup page is http://10.42.0.1/ (or the mDNS name, published by Avahi on the hotspot link)."""
    net = HOTSPOT_NETWORK
    return "\n".join([
        "# generated by hifi-netd - do not edit (lives in RAM only)",
        "port=0",
        f"interface={iface}",
        "bind-interfaces",
        "except-interface=lo",
        f"listen-address={HOTSPOT_ADDRESS}",
        f"dhcp-range={DHCP_RANGE[0]},{DHCP_RANGE[1]},{net.netmask},1h",
        "dhcp-option=option:router",
        "dhcp-option=option:dns-server",
        "dhcp-authoritative",
        "dhcp-rapid-commit",
        f"dhcp-leasefile={run_dir}/dnsmasq.leases",
        f"pid-file={run_dir}/dnsmasq.pid",
        "no-resolv",
        "no-hosts",
        "no-poll",
        "",
    ])


def _ip_sections(ip: dict) -> tuple[list[str], list[str]]:
    """[Network] lines and extra sections for one interface's address configuration."""
    v4, v6 = ip["ipv4"], ip["ipv6"]
    net: list[str] = []
    extra: list[str] = []
    dhcp4 = v4["method"] == "dhcp"
    net.append(f"DHCP={'ipv4' if dhcp4 else 'no'}")       # DHCPv6 is started by router advertisements (managed/other flag)
    if v6["method"] == "off":
        net += ["LinkLocalAddressing=no", "IPv6AcceptRA=no"]
    else:
        net += ["LinkLocalAddressing=ipv6", f"IPv6AcceptRA={'yes' if v6['method'] == 'auto' else 'no'}"]
    for v in (v4, v6):
        if v["method"] == "static":
            net.append(f"Address={v['address']}")
            if v["gateway"]:
                net.append(f"Gateway={v['gateway']}")
            net += [f"DNS={d}" for d in v["dns"]]
    if dhcp4:
        extra += ["", "[DHCPv4]", "SendHostname=yes", "UseHostname=no", "UseDNS=yes", "UseNTP=yes", "UseDomains=no"]
    if v6["method"] == "auto":
        extra += ["", "[IPv6AcceptRA]", "UseDNS=yes", "UseDomains=no"]
    return net, extra


def networkd_files(cfg: dict, ethernet: list[str], wlan: str | None, wlan_role: str) -> dict[str, str]:
    """Files for /run/systemd/network. ``wlan_role``: client | hotspot | off. Names sort before Buildroot's fallback dhcp.network."""
    files: dict[str, str] = {}
    head = "# generated by hifi-netd - do not edit\n"
    if ethernet:
        net, extra = _ip_sections(cfg["ethernet"])
        files["10-hifi-ethernet.network"] = head + "\n".join(
            ["[Match]", f"Name={' '.join(ethernet)}", "", "[Network]", *net, *extra, ""])
    if wlan and wlan_role == "client" and cfg.get("wifi"):
        net, extra = _ip_sections(cfg["wifi"])
        files["11-hifi-wifi.network"] = head + "\n".join(
            ["[Match]", f"Name={wlan}", "", "[Network]", *net, *extra, ""])
    elif wlan and wlan_role == "hotspot":
        files["11-hifi-wifi.network"] = head + "\n".join(
            ["[Match]", f"Name={wlan}", "", "[Link]", "RequiredForOnline=no", "", "[Network]",
             f"Address={HOTSPOT_ADDRESS}/{HOTSPOT_NETWORK.prefixlen}", "ConfigureWithoutCarrier=yes", "LinkLocalAddressing=ipv6",
             "IPv6AcceptRA=no", "DHCP=no", "IPv6SendRA=no", ""])
    return files


def nftables(http_port: int, https_port: int, stream_port: int, hotspot_iface: str | None = None) -> str:
    """Default-deny inbound ruleset (inet = IPv4 + IPv6). Replaces our table atomically (one nft transaction); other tables untouched.

    Everyone: loopback, replies to own connections, essential ICMP/ICMPv6 incl. neighbour discovery, mDNS.
    Hotspot clients (``hotspot_iface``): DHCP and the WebUI (HTTP/HTTPS) only - no stream port, no other service, nothing forwarded.
    Other interfaces (LAN via Ethernet or client Wi-Fi): WebUI, the stream port for Lyrion/players, DHCPv4/DHCPv6 client replies and
    replies to the Lyrion discovery broadcast."""
    web = f"{http_port}, {https_port}"
    lines = [
        "#!/usr/sbin/nft -f",
        "# generated by hifi-netd (docs/NETWORK.md, 'Firewall')",
        f"table inet {NFT_TABLE}",
        f"delete table inet {NFT_TABLE}",
        f"table inet {NFT_TABLE} {{",
        "\tchain input {",
        "\t\ttype filter hook input priority filter; policy drop;",
        '\t\tiif "lo" accept',
        "\t\tct state invalid drop",
        "\t\tct state established,related accept",
        "\t\tmeta l4proto icmp icmp type { destination-unreachable, time-exceeded, parameter-problem } accept",
        "\t\tmeta l4proto icmp icmp type echo-request limit rate 10/second burst 20 packets accept",
        "\t\tmeta l4proto ipv6-icmp icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, "
        "nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert, mld-listener-query } accept",
        "\t\tmeta l4proto ipv6-icmp icmpv6 type echo-request limit rate 10/second burst 20 packets accept",
        "\t\tudp dport 5353 accept",
    ]
    if hotspot_iface:
        lines.append(f'\t\tiifname "{hotspot_iface}" jump hotspot')
    lines += [
        "\t\tudp sport 67 udp dport 68 accept",
        "\t\tip6 saddr fe80::/10 udp sport 547 udp dport 546 accept",
        f"\t\tudp sport {LYRION_DISCOVERY_PORT} udp dport 1024-65535 accept",
        f"\t\ttcp dport {{ {web}, {stream_port} }} accept",
        "\t}",
    ]
    if hotspot_iface:
        lines += [
            "\tchain hotspot {",
            "\t\tudp dport 67 accept",
            f"\t\ttcp dport {{ {web} }} accept",
            "\t\tdrop",
            "\t}",
        ]
    lines += [
        "\tchain forward {",
        "\t\ttype filter hook forward priority filter; policy drop;",
        "\t}",
        "}",
        "",
    ]
    return "\n".join(lines)
